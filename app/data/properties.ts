export const formatPrice = (price: number): string => {
  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: 0,
  }).format(price)
}

export const formatSqft = (sqft: number): string => {
  return new Intl.NumberFormat("en-US").format(sqft)
}

export const getPropertyTypeLabel = (type: Property["propertyType"]): string => {
  const labels: Record<Property["propertyType"], string> = {
    house: "House",
    apartment: "Apartment",
    condo: "Condo",
    townhouse: "Townhouse",
    studio: "Studio",
  }
  return labels[type]
}
